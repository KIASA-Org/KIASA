// Copies the KIASA leaf from the site into the app, exactly: the drawing must never be redrawn or
// simplified, so it is generated from the site's own files rather than kept by hand.
//   node tools/export-leaf.cjs           writes Core/LeafDrawing.g.cs
//   node tools/export-leaf.cjs --check   fails if that file no longer matches the site
const path = require("path");
const fs = require("fs");
const Module = require("module");

const WEB = path.resolve(__dirname, "../../web");
const ts = require(path.join(WEB, "node_modules/typescript"));
const INTRO = path.join(WEB, "src/components/intro");
const OUT = path.resolve(__dirname, "../Core/LeafDrawing.g.cs");

/** Loads one of the site's TypeScript files. */
function load(file) {
  const source = fs.readFileSync(path.join(INTRO, file), "utf8");
  const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
  const module = new Module(file);
  module.paths = [];
  module._compile(outputText, path.join(INTRO, file));
  return module.exports;
}

const { STROKES, DEW, VIEW } = load("geometry.ts");
const { inkWidth, glint, RING, INK } = load("drawing.ts");

const text = value => JSON.stringify(value);
const number = value => (Number.isInteger(value) ? `${value}` : `${value}`);
const lines = STROKES.map(stroke => `        new("${stroke.id}", "${stroke.role}", ${number(inkWidth(stroke))}, ${number(stroke.length)}, ${text(stroke.d)}),`);
const drops = DEW.map(drop => `        new(${number(drop.x)}, ${number(drop.y)}, ${number(drop.r)}, ${text(glint(drop))}),`);

const output = `// Generated by tools/export-leaf.cjs from the site's components/intro. Do not edit: the KIASA leaf
// must never be redrawn or simplified. Change it on the site and run that again.
namespace LiveDesk.Core;

public static class LeafDrawing
{
    public const double ViewX = ${VIEW.x}, ViewY = ${VIEW.y}, ViewSize = ${VIEW.size};
    public const double Ring = ${RING};
    public const string Ink = "${INK}";

    public readonly record struct Line(string Id, string Role, double Ink, double Length, string Path);
    public readonly record struct Drop(double X, double Y, double R, string Glint);

    public static readonly Line[] Lines =
    [
${lines.join("\n")}
    ];

    public static readonly Drop[] Drops =
    [
${drops.join("\n")}
    ];
}
`.replace(/\n/g, "\r\n");

if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== output) { console.error("Core/LeafDrawing.g.cs does not match the site's leaf: run tools/export-leaf.cjs"); process.exit(1); }
  console.log(`the app's leaf matches the site's: ${STROKES.length} lines, ${DEW.length} dew drops`);
} else {
  fs.writeFileSync(OUT, output);
  console.log(`wrote ${path.basename(OUT)}: ${STROKES.length} lines, ${DEW.length} dew drops`);
}
